<?php

declare(strict_types=1);

return [

    /*
    |--------------------------------------------------------------------------
    | AI 相談(Gemini チャットボット)機能スイッチ
    |--------------------------------------------------------------------------
    |
    | false の間は /ai-chat 配下のルート自体が登録されない(routes/web.php)ため、
    | フローティングウィジェット・フル画面ともに一切表示・利用できない。
    | GEMINI_API_KEY が未設定でも本スイッチが true ならルート・画面は動作するが、
    | AI 応答は常にエラー(「AI が応答できませんでした」)としてグレースフルに失敗する。
    |
    */
    'enabled' => (bool) env('AI_CHAT_ENABLED', false),

    'gemini' => [
        'model' => env('GEMINI_MODEL', 'gemini-2.5-flash'),
        'timeout' => (int) env('GEMINI_TIMEOUT', 20),
    ],

    /*
    |--------------------------------------------------------------------------
    | 受講生 1 人あたりの 1 日の送信回数上限
    |--------------------------------------------------------------------------
    |
    | 「本日(Asia/Tokyo)」に role=user のメッセージを何件送ったかで判定する。AI 応答が
    | エラーになった回数は上限を消費しない(送信自体は成功しているため)。
    |
    */
    'daily_message_limit' => (int) env('AI_CHAT_DAILY_MESSAGE_LIMIT', 30),

    /*
    |--------------------------------------------------------------------------
    | 教材文脈として AI に渡す Section 本文の最大文字数
    |--------------------------------------------------------------------------
    |
    | 教材本文をそのままプロンプトに含めるため、極端に長い Section で無駄なトークン消費が
    | 起きないよう上限で切り詰める(会話履歴の「件数のみで制御」とは別軸の安全弁)。
    |
    */
    'section_context_max_chars' => (int) env('AI_CHAT_SECTION_CONTEXT_MAX_CHARS', 4000),

    /*
    |--------------------------------------------------------------------------
    | プロンプトに含める過去メッセージの件数
    |--------------------------------------------------------------------------
    |
    | トークン数ではなく件数で履歴を打ち切る(自前のトークンカウントは行わない)。
    | エラーになった過去のやり取りは履歴に含めない。
    |
    */
    'history_message_limit' => (int) env('AI_CHAT_HISTORY_MESSAGE_LIMIT', 10),

];
